import { DemoStorage } from "./storage";
export async function openDemo() {
  const s = new DemoStorage();
  if (localStorage.getItem(DemoStorage.key) === null) {
    await s.create(
      "생각을 연결하는 작은 습관",
      `메모는 완성된 생각의 기록이 아니라, 생각이 시작되는 자리일지도 모릅니다.\n\n## 흩어진 조각에서 시작하기\n\n책을 읽다가 밑줄 친 문장, 산책하며 떠오른 질문, 아직 이름 붙이지 못한 아이디어. 우선 [[덤프]]에 가볍게 내려놓아 보세요.\n\n**정리보다 먼저, 수집.** 충분히 쌓인 조각에서 한 가지 생각을 골라 자기만의 노트로 옮깁니다. 서로의 연결이 서서히 보이기 시작합니다.\n\n## 작은 연결 하나\n\n좋은 질문은 종종 다른 질문으로 이어집니다. [[좋은 질문을 모으는 일]]처럼요. \`[[이건 코드 예시]]\`는 연결되지 않습니다.\n\n마음에 드는 문장을 선택한 뒤 **새 노트로 옮기기**를 눌러 보세요. 원래 자리에는 연결이 남습니다.\n\n> 서두르지 않아도 괜찮아요. 오늘의 생각을 한 줄 남기는 것부터.\n\n[디지털 정원에 관하여](https://maggieappleton.com/garden-history)`,
    );
    await s.create(
      "좋은 질문을 모으는 일",
      `답을 모으는 대신, 오래 붙잡고 싶은 질문을 모읍니다.\n\n- 나는 어떤 생각을 자꾸 되풀이할까?\n- 최근에 마음을 바꾼 순간은 언제였을까?\n- 이 생각은 어디에서 왔을까?\n\n[[생각을 연결하는 작은 습관]]으로 돌아가 보면, 질문도 작은 조각에서 시작합니다.`,
    );
    await s.create(
      "덤프",
      `## 아직 이름 없는 생각들\n\n서로 관계없어 보이는 두 생각을 나란히 놓아 보기.\n\n나중에 읽을 글, 한 문장 메모, 어딘가에서 주운 질문을 이곳에 모아 둡니다.\n\n정리되지 않은 채로도 충분합니다.`,
    );
    await s.create(
      "산책과 생각의 속도",
      `걷는 속도로 생각하면, 놓쳤던 것이 보입니다.\n\n오늘 산책에서 발견한 것:\n\n- 골목 끝 작은 나무의 계절\n- 목적 없이 걷는 시간의 여유\n- 어떤 문장은 책상 밖에서 완성된다는 것`,
    );
  }
  return s;
}
